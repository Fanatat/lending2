import type { SystemKey } from "./systemCopy";

export interface FlowLane {
  /** Optional lane caption when a system runs several pipelines side by side. */
  label?: string;
  steps: string[];
}

export interface ProjectMeta {
  slug: string;
  title: string;
  /** Key into SYSTEM_COPY / systemStatus. */
  system: SystemKey;
  /** Dashboard section id, for "назад к блоку на дашборде". */
  anchor: string;
  /** Hidden systems stay out of the prev/next chain so the egg isn't spoiled. */
  hidden?: boolean;
  /**
   * "Как устроено": the pipeline retold step by step. Every step restates
   * the system's own published copy (lib/systemCopy + the section line);
   * nothing here adds facts the dashboard doesn't already claim.
   */
  flow: FlowLane[];
  /** Rules and constraints the system is built around, shown under the flow. */
  rules: string[];
}

