export function getProjectMeta(slug: string): ProjectMeta | undefined {
  return PROJECTS.find((p) => p.slug === slug);
}

/** Neighbours in the public chain (hidden systems are skipped, but can still navigate out). */
export function getProjectNeighbours(slug: string) {
  const chain = PROJECTS.filter((p) => !p.hidden || p.slug === slug);
  const i = chain.findIndex((p) => p.slug === slug);
  const n = chain.length;
  // i >= 0: the current slug is always kept in the chain.
  return { prev: chain[(i - 1 + n) % n]!, next: chain[(i + 1) % n]! };
}
